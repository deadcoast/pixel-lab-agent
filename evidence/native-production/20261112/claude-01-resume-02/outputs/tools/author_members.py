"""Append the production-member candidates (delivered files) for the family stages."""
import json, hashlib, sys
from pathlib import Path
root, src, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
doc = json.loads(src.read_text(encoding="utf-8"))
G = "r.acf329804ba043b7."; F = "robot-directions-family."
REF = lambda i: {"$ref": i}; SYM = lambda v: {"$symbol": v}
def sha(p): return hashlib.sha256((root/p).read_bytes()).hexdigest()
members = {
 "east": {"sample": "candidate.east.raw", "prov": "reused-generated", "note": "byte-identical copy of the official provider east (object 2a3cb51a-6cf7-485d-8441-3c3db762cc9d, job " + G + "request); generated by PixelLab, no edit"},
 "north": {"sample": "candidate.north.raw", "prov": "reused-generated", "note": "byte-identical copy of the official provider north (object 2a3cb51a-6cf7-485d-8441-3c3db762cc9d, job " + G + "request); generated by PixelLab, no edit"},
 "west": {"sample": "candidate.west.edited", "prov": "reused-edited", "note": "byte-identical copy of candidate.west.edited: deterministic horizontal mirror of the official east; NOT an official generated west (the raw provider west candidate.west.raw was rejected: no front edge)"},
}
ids = {r["id"] for r in doc["records"]}
for d, m in members.items():
    path = f"assets/robot/{d}.png"; cid = F + d + ".member"
    assert cid not in ids
    doc["records"].append({"id": cid, "kind": "X", "fields": {
        "nm": f"Delivered {d} member at the controller path",
        "ur": path, "dg": sha(path), "ct": REF(G + f"contract.{d}"), "kd": SYM("sprite"), "of": REF(F + d + ".output"),
        "mt": {"provenance": m["prov"], "sample_candidate": m["sample"], "note": m["note"], "copied_at": "2026-11-12T08:47:38+00:00"},
        "tg": ["robot.directions", d, m["prov"]]}})
    print(cid, path, sha(path))
doc["revision"] = int(doc["revision"]) + 1
doc.setdefault("format", 2)
out.write_text(json.dumps(doc, indent=1, ensure_ascii=False), encoding="utf-8")
